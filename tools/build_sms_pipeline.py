# tools/build_sms_pipeline.py
#
# PLAIN-ENGLISH WHAT THIS IS: the SMS reader (sms-parser-backend/Code.js) decides "is this a transaction, what are its details, is it a
# duplicate". The main backend must make the SAME decisions on a person's private copy, so this copies that part of Code.js WORD FOR
# WORD into backend/smsPipelineCore.js (wrapped so its names cannot clash with anything else). There is one source of truth: edit
# Code.js, run this, commit both. A test (backend/tests/smsPipelineCore.test.js) fails if the copy is out of date.
#
# Run:  python tools/build_sms_pipeline.py          (writes backend/smsPipelineCore.js)
#       python tools/build_sms_pipeline.py --check  (exit 1 if the copy is out of date)

import os
import sys

ROOT = os.path.join(os.path.dirname(__file__), "..")
SRC = os.path.join(ROOT, "sms-parser-backend", "Code.js")
DST = os.path.join(ROOT, "backend", "smsPipelineCore.js")
BEGIN = "// ==== SMS-PIPELINE-CORE-BEGIN ===="
END = "// ==== SMS-PIPELINE-CORE-END ===="

EXPORTS = ["classifySms", "classifyDetail", "ruleParser", "isDuplicate", "isKnownSender", "hasRupeeAmount", "hasMoneyMovementSignal", "setExtraSenders", "bankFromSender", "findTransactionAmount", "sameMessageDay"]


def build():
    text = open(SRC, encoding="utf-8").read().replace("\r\n", "\n")
    b = text.index(BEGIN)
    b = text.index("\n", text.index("\n", b) + 1) + 1          # skip the two marker comment lines
    e = text.index(END)
    core = text[b:e].rstrip() + "\n"
    out = []
    out.append("// backend/smsPipelineCore.js  --  GENERATED by tools/build_sms_pipeline.py from sms-parser-backend/Code.js. DO NOT EDIT BY HAND.\n")
    out.append("//\n")
    out.append("// The SMS reader's own decisions (is it a transaction, what are its details, is it a duplicate), copied word for word and wrapped\n")
    out.append("// so its names cannot clash with the rest of the backend. It reads past rows through getSheet(), which here is the person's\n")
    out.append("// private copy (dbSs_). Used by smsIn.js.\n")
    out.append("var SmsPipeline = (function(getSheet, TRANSACTION_SHEET){\n")
    out.append(core)
    out.append("\n  return {\n")
    out.append(",\n".join("    %s: %s" % (n, n) for n in EXPORTS))
    out.append("\n  };\n")
    out.append("})(function(name){ return dbSs_().getSheetByName(name); }, \"Transactions\");\n")
    return "".join(out)


if __name__ == "__main__":
    new = build()
    if "--check" in sys.argv:
        old = open(DST, encoding="utf-8").read().replace("\r\n", "\n") if os.path.exists(DST) else ""
        sys.exit(0 if old == new else 1)
    with open(DST, "w", encoding="utf-8", newline="\n") as f:
        f.write(new)
    print("wrote", DST, len(new.splitlines()), "lines")
